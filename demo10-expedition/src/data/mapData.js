// Loot spot metadata
const LOOT_SPOTS = {};

(function initLootSpots() {
    for (let r = 0; r < MAP_HEIGHT; r++) {
        for (let c = 0; c < MAP_WIDTH; c++) {
            if (CITY_MAP[r][c] === TILE_TYPES.LOOT) {
                const key = `${r},${c}`;
                if (r < 10) LOOT_SPOTS[key] = { table: 'commercial', items: 3, searched: false };
                else if (r < 20) LOOT_SPOTS[key] = { table: 'urban', items: 4, searched: false };
                else LOOT_SPOTS[key] = { table: 'residential', items: 3, searched: false };
            }
        }
    }
})();

// Player start position (safe house)
const PLAYER_START = { row: 27, col: 3 };

// Escape point position
const ESCAPE_POINT = { row: 24, col: 23 };

// Get walkable road tiles for enemy spawning
function getSpawnableTiles() {
    const tiles = [];
    for (let r = 1; r < MAP_HEIGHT - 1; r++) {
        for (let c = 1; c < MAP_WIDTH - 1; c++) {
            if (CITY_MAP[r][c] === TILE_TYPES.ROAD || CITY_MAP[r][c] === TILE_TYPES.RUBBLE) {
                tiles.push({ row: r, col: c });
            }
        }
    }
    return tiles;
}
